"""Estimates each club's hidden traits from the generated season data.

The match engine builds each shot's rate as a product of multipliers
(attack, defense, comeback, protect-lead, fatigue, ten-men). Taking logs
turns that product into a sum, which is exactly the structure a Poisson
regression fits — so we can run the mechanism backwards: regress each
team's observed xG output on indicators for its game state (trailing,
leading, red card, after minute 75), and read the hidden trait off each
coefficient.
"""

import numpy as np
import pandas as pd
import statsmodels.api as sm


def _match_minute_states(home_team: str, away_team: str, shots: pd.DataFrame,
                          red_cards: pd.DataFrame) -> pd.DataFrame:
    """Reconstructs, for minutes 1..90, the score/red-card state in effect
    for that minute's rate calculation (mirrors the match engine's own
    bookkeeping: a red card issued in minute M applies from minute M; a
    goal scored in minute M applies starting minute M+1)."""
    goals_by_minute: dict[int, list[str]] = {}
    for _, row in shots[shots.is_goal].iterrows():
        goals_by_minute.setdefault(int(row.minute), []).append(row.team)

    cards_by_minute: dict[int, list[str]] = {}
    for _, row in red_cards.iterrows():
        cards_by_minute.setdefault(int(row.minute), []).append(row.team)

    home_score = away_score = 0
    home_card = away_card = False
    rows = []
    for minute in range(1, 91):
        for team in cards_by_minute.get(minute, []):
            if team == home_team:
                home_card = True
            elif team == away_team:
                away_card = True

        rows.append({"minute": minute, "home_score": home_score, "away_score": away_score,
                     "home_card": home_card, "away_card": away_card})

        for team in goals_by_minute.get(minute, []):
            if team == home_team:
                home_score += 1
            elif team == away_team:
                away_score += 1

    return pd.DataFrame(rows)


def _collapse_to_segments(states: pd.DataFrame) -> pd.DataFrame:
    """Groups consecutive minutes with identical state into segments."""
    states = states.copy()
    states["late"] = states.minute > 75
    key_cols = ["home_score", "away_score", "home_card", "away_card", "late"]
    changed = (states[key_cols] != states[key_cols].shift()).any(axis=1)
    states["segment_id"] = changed.cumsum()

    return states.groupby("segment_id").agg(
        start_minute=("minute", "min"), end_minute=("minute", "max"),
        home_score=("home_score", "first"), away_score=("away_score", "first"),
        home_card=("home_card", "first"), away_card=("away_card", "first"),
        late=("late", "first"),
    ).reset_index(drop=True)


def _team_rows_for_match(match: pd.Series, match_shots: pd.DataFrame,
                          match_cards: pd.DataFrame) -> list[dict]:
    """Expands one match into (team, segment) rows: exposure minutes, shots
    taken, and xG generated by that team while the game was in that state."""
    home_team, away_team = match.home_team, match.away_team
    states = _match_minute_states(home_team, away_team, match_shots, match_cards)
    segments = _collapse_to_segments(states)

    rows = []
    for _, seg in segments.iterrows():
        exposure = seg.end_minute - seg.start_minute + 1
        window = (match_shots.minute >= seg.start_minute) & (match_shots.minute <= seg.end_minute)

        for team, opponent, is_home in ((home_team, away_team, True), (away_team, home_team, False)):
            own_score = seg.home_score if is_home else seg.away_score
            opp_score = seg.away_score if is_home else seg.home_score
            own_card = seg.home_card if is_home else seg.away_card
            opp_card = seg.away_card if is_home else seg.home_card

            team_shots = match_shots[window & (match_shots.team == team)]
            rows.append({
                "season": match.season, "match_id": match.match_id,
                "shooter": team, "opponent": opponent, "is_home": is_home,
                "exposure": exposure, "shot_count": len(team_shots), "xg_sum": team_shots.xg.sum(),
                "trailing": own_score < opp_score, "own_card": own_card, "opp_card": opp_card,
                "late": seg.late,
            })
    return rows


def build_regression_table(matches: pd.DataFrame, shots: pd.DataFrame,
                            red_cards: pd.DataFrame) -> pd.DataFrame:
    """Builds the full (team, match, segment) panel used to fit the GLM."""
    all_rows = []
    shots_by_match = {mid: g for mid, g in shots.groupby("match_id")}
    cards_by_match = {mid: g for mid, g in red_cards.groupby("match_id")}
    empty_cards = red_cards.iloc[0:0]

    for _, match in matches.iterrows():
        match_shots = shots_by_match.get(match.match_id)
        match_cards = cards_by_match.get(match.match_id, empty_cards)
        all_rows.extend(_team_rows_for_match(match, match_shots, match_cards))

    return pd.DataFrame(all_rows)


def compute_weights(seasons: pd.Series, half_life: float | None, latest_season: int) -> np.ndarray:
    """Recency weight per row. half_life=None means no decay (every season counts equally)."""
    if half_life is None:
        return np.ones(len(seasons))
    seasons_ago = latest_season - seasons.to_numpy()
    return np.exp(-np.log(2) / half_life * seasons_ago)


def _masked_team_dummies(trigger: pd.Series, team_series: pd.Series, prefix: str,
                          teams: list[str]) -> pd.DataFrame:
    """One column per team: 1 if (team_series == team) AND trigger, else 0.
    Not reference-dropped — most rows have trigger=False, so there's no
    dummy-variable trap (unlike the shooter/opponent main effects below)."""
    dummies = pd.get_dummies(team_series, prefix=prefix)
    dummies = dummies.reindex(columns=[f"{prefix}_{t}" for t in teams], fill_value=0)
    return dummies.multiply(trigger.astype(int), axis=0)


def build_design_matrix(df: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    """Builds the GLM design matrix. shooter/opponent use one dropped reference
    level each (standard treatment coding, avoids collinearity with the
    intercept); the five state x team interaction groups keep all 20 teams
    since they're only active on a subset of rows."""
    shooter_dummies = pd.get_dummies(df.shooter, prefix="atk")
    shooter_dummies = shooter_dummies.reindex(columns=[f"atk_{t}" for t in teams], fill_value=0)
    shooter_dummies = shooter_dummies.drop(columns=[f"atk_{teams[0]}"])

    opponent_dummies = pd.get_dummies(df.opponent, prefix="def")
    opponent_dummies = opponent_dummies.reindex(columns=[f"def_{t}" for t in teams], fill_value=0)
    opponent_dummies = opponent_dummies.drop(columns=[f"def_{teams[0]}"])

    # Shooter-trailing and opponent-leading are literally the same event (the one
    # team is trailing iff the other is leading), so a full 20-column dummy group
    # for each shares the exact same per-row total -> rank-deficient by 1. Drop one
    # reference column from the "prolead" side only; fit_traits() then re-splits
    # the gauge freedom between the two groups via a symmetry assumption.
    trail_shooter = _masked_team_dummies(df.trailing, df.shooter, "trail", teams)
    prolead_opp = _masked_team_dummies(df.trailing, df.opponent, "prolead", teams)
    prolead_opp = prolead_opp.drop(columns=[f"prolead_{teams[0]}"])
    cardA_shooter = _masked_team_dummies(df.own_card, df.shooter, "cardA", teams)
    cardD_opp = _masked_team_dummies(df.opp_card, df.opponent, "cardD", teams)
    late_opp = _masked_team_dummies(df.late, df.opponent, "late", teams)

    return pd.concat([
        pd.Series(1.0, index=df.index, name="intercept"),
        df.is_home.astype(float).rename("home"),
        shooter_dummies.astype(float), opponent_dummies.astype(float),
        trail_shooter.astype(float), prolead_opp.astype(float),
        cardA_shooter.astype(float), cardD_opp.astype(float), late_opp.astype(float),
    ], axis=1)


def fit_traits(df: pd.DataFrame, teams: list[str], weights: np.ndarray) -> pd.DataFrame:
    """Fits the Poisson GLM and converts coefficients back into traits on
    the same scale as the true traits (attack/defense centered so the
    league average is 1.0; the rest read directly off their coefficient,
    since they're not relative to an arbitrary reference team)."""
    X = build_design_matrix(df, teams)
    y = df.xg_sum.to_numpy()
    offset = np.log(df.exposure.to_numpy())

    model = sm.GLM(y, X.to_numpy(), family=sm.families.Poisson(), offset=offset, freq_weights=weights)
    result = model.fit()
    params = pd.Series(result.params, index=X.columns)

    def coef(prefix: str, team: str) -> float:
        col = f"{prefix}_{team}"
        return params[col] if col in params.index else 0.0  # reference team's dummy is implicitly 0

    # trail_t and prolead_t share one degree of freedom (see build_design_matrix):
    # shooter-trailing and opponent-leading are the same event, so the data pins
    # down each GROUP's team-to-team differences but not the absolute split
    # between "comeback boost" and "lead protection" (shifting one group up and
    # the other down by the same log-amount leaves every prediction unchanged).
    # Resolve that single free constant by anchoring both groups' average back
    # to log(1.15) — the known mean of their shared creation distribution,
    # uniform(1.0, 1.3) in league.py. This is a fact about the simulator's
    # design, not a peek at this run's actual true_traits.csv values.
    log_trail = np.array([coef("trail", t) for t in teams])          # = log(comeback_t) - c
    log_prolead = np.array([coef("prolead", t) for t in teams])      # = -log(protect_lead_t) - c
    target = np.log(1.15)
    c = (log_trail.mean() - log_prolead.mean()) / 2 - target

    rows = []
    for team, trail, prolead in zip(teams, log_trail, log_prolead):
        resilience_attack_side = np.exp(coef("cardA", team))
        resilience_defense_side = np.exp(-coef("cardD", team))
        rows.append({
            "team": team,
            "attack": np.exp(coef("atk", team)),
            "defense": np.exp(-coef("def", team)),
            "comeback_factor": np.exp(trail - c),
            "protect_lead_factor": np.exp(-prolead - c),
            "fatigue_factor": np.exp(-coef("late", team)),
            "ten_men_resilience": (resilience_attack_side + resilience_defense_side) / 2,
        })

    traits = pd.DataFrame(rows).set_index("team")
    for col in ("attack", "defense"):  # recenter: remove the arbitrary reference-team baseline
        traits[col] /= np.exp(np.log(traits[col]).mean())
    return traits


def compute_state_exposure(table: pd.DataFrame, teams: list[str]) -> pd.DataFrame:
    """Minutes of data behind each club's state-dependent trait estimate —
    used to decide how much to shrink each club's estimate toward the
    league average."""
    def minutes(mask: pd.Series, by: str) -> pd.Series:
        return table[mask].groupby(by).exposure.sum().reindex(teams, fill_value=0)

    exposure = pd.DataFrame(index=teams)
    exposure["comeback_factor"] = minutes(table.trailing, "shooter")
    exposure["protect_lead_factor"] = minutes(table.trailing, "opponent")
    exposure["ten_men_resilience"] = minutes(table.own_card, "shooter") + minutes(table.opp_card, "opponent")
    exposure["fatigue_factor"] = minutes(table.late, "opponent")
    return exposure


def shrink_traits(estimated: pd.DataFrame, exposure: pd.DataFrame, traits: list[str]) -> pd.DataFrame:
    """Pulls each club's estimate toward the league average, by an amount
    that depends on how little data backs it (James-Stein-style shrinkage:
    weight = exposure / (exposure + k), so a club with roughly the typical
    (median) amount of data gets pulled about halfway)."""
    shrunk = estimated.copy()
    for trait in traits:
        k = exposure[trait].median()
        weight = exposure[trait] / (exposure[trait] + k)
        league_mean = estimated[trait].mean()
        shrunk[trait] = league_mean + weight * (estimated[trait] - league_mean)
    return shrunk
